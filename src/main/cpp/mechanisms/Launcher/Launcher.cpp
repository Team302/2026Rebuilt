void Launcher::Periodic()
{
	// This function is called once per loop by the CommandScheduler (all modes) before any
	// scheduled command's execute(). It performs the per-loop housekeeping that used to live
	// in StateMgr::RunCommonTasks(): refresh cached sensor data, apply manual control, and
	// push the active control requests to the motors.
	RefreshCachedData();
	UpdateCachedLoggingValues();

	Update();

	if (frc::DriverStation::IsDisabled())
	{
		InitializeLauncher();
		m_targetCalculator->ForceUpdateChassisPose();
	}

	SetLauncherProtect();

	if (!m_tuningLauncher)
	{
		m_targetCalculator->UpdateTargetOffset();
	}
	CalculateTargets();
	UpdateLauncherTargets();

	// Logging
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "Current State", GetCurrentStateName());
}

