void Launcher::CalculateTargets()
{

	if (m_turretEnabled)
	{
		m_targetTurretAngle = m_targetCalculator->GetLauncherTarget(m_cachedTurretPosition);
	}
	else
	{
		m_targetTurretAngle = 180_deg;
		m_chassis->SetTargetChassisRotation(m_targetCalculator->GetChassisTargetForLaunching());
	}
	m_distanceToTarget = m_targetCalculator->GetLauncherDistanceToTarget();
	if (m_allianceZoneManager->IsInAllianceZone())
	{
		m_targetHoodAngle = InterpolateUtils::linearInterpolate(m_scoringDistanceArray, m_scoringHoodAngleArray, m_distanceToTarget);
		m_targetLauncherAngularVelocity = InterpolateUtils::linearInterpolate(m_scoringDistanceArray, m_scoringLauncherVelocityArray, m_distanceToTarget);
	}
	else
	{
		m_targetHoodAngle = InterpolateUtils::linearInterpolate(m_passingDistanceArray, m_passingHoodAngleArray, units::length::foot_t(m_distanceToTarget));
		m_targetLauncherAngularVelocity = InterpolateUtils::linearInterpolate(m_passingDistanceArray, m_passingLauncherVelocityArray, units::length::foot_t(m_distanceToTarget));
	}

	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "Distance", m_distanceToTarget.value());
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "Target Hood", m_targetHoodAngle.value());
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "Target Launcher Velocity", m_targetLauncherAngularVelocity.value());
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "turret Target", m_targetTurretAngle.value());
}

void Launcher::UpdateLauncherTargets()
{
	int currentState = GetCurrentState();

	if (currentState == STATE_NAMES::STATE_OFF || currentState == STATE_NAMES::STATE_INITIALIZE || currentState == STATE_NAMES::STATE_MANUAL_LAUNCH || m_tuningLauncher)
	{
		return;
	}

	UpdateTargetHoodPositionDegreesHood(m_targetHoodAngle);

	if (m_turretEnabled)
	{
		UpdateTargetTurretPositionDegreesTurret(m_targetTurretAngle);
	}

	if (currentState == STATE_NAMES::STATE_LAUNCH || currentState == STATE_NAMES::STATE_PREPARE_TO_LAUNCH)
	{
		UpdateTargetLauncherVelocityLauncher(m_targetLauncherAngularVelocity);
	}
}

void Launcher::InitializeLauncher()
{
	bool turretReverseLimitSwitchTripped = false;
	bool turretForwardLimitSwitchTripped = false;

	if (m_turretEnabled)
	{
		turretReverseLimitSwitchTripped = m_turretMotor->GetReverseLimit().GetValue() == ctre::phoenix6::signals::ReverseLimitValue::ClosedToGround;
		turretForwardLimitSwitchTripped = m_turretMotor->GetForwardLimit().GetValue() == ctre::phoenix6::signals::ForwardLimitValue::ClosedToGround;
		if (turretForwardLimitSwitchTripped)
		{
			m_turretMotor->SetPosition(m_maxTurretAngle);
			m_turretHasReset = true;
		}
		else if (turretReverseLimitSwitchTripped)
		{
			m_turretMotor->SetPosition(m_minTurretAngle);
			m_turretHasReset = true;
		}
	}

	auto hoodReverseLimitSwitchTripped = m_hoodMotor->GetReverseLimit().GetValue() == ctre::phoenix6::signals::ReverseLimitValue::ClosedToGround;

	if ((m_turretEnabled && m_turretHasReset && hoodReverseLimitSwitchTripped) ||
		(!m_turretEnabled && hoodReverseLimitSwitchTripped) ||
		frc::RobotBase::IsSimulation())
	{
		m_launcherInitialized = true;
	}
}

void Launcher::SetLauncherProtect()
{
	if (TeleopControl::GetInstance()->IsButtonPressed(TeleopControlFunctions::LAUNCHER_OFF))
	{
		if (m_launcherOffButtonReleased)
		{
			m_launcherProtectedMode = !m_launcherProtectedMode;
		}
		m_launcherOffButtonReleased = false;
	}
	else
	{
		m_launcherOffButtonReleased = true;
	}
}

bool Launcher::IsTurretAtTarget()
{
	m_cachedTurretAtTarget = false;
	if (frc::RobotBase::IsSimulation() && !(GetCurrentState() == STATE_NAMES::STATE_LAUNCHER_TUNING))
	{
		return true;
	}
	if (m_turretEnabled)
	{
		if (m_hasValidTurretAngle)
		{
			units::angle::degree_t turretError = m_cachedTurretPosition - m_targetTurretAngle;
			m_cachedTurretAtTarget = ((units::math::abs(turretError) < m_turretAngleThreshold));
		}
	}
	else
	{
		m_cachedTurretAtTarget = true; // m_chassis->IsChassisAtRotationTarget();
	}

	return m_cachedTurretAtTarget;
}

void Launcher::UpdateTurretEnabled()
{
	if (TeleopControl::GetInstance()->IsButtonPressed(TeleopControlFunctions::TURRET_ENABLE) && m_turretEnabledButtonReleased)
	{
		if (m_turretEnabledButtonReleased)
			m_turretEnabled = !m_turretEnabled;
	}
	m_turretEnabledButtonReleased = !TeleopControl::GetInstance()->IsButtonPressed(TeleopControlFunctions::TURRET_ENABLE);
	RobotState::GetInstance()->PublishStateChange(RobotStateChanges::StateChange::TurretEnabled_Bool, m_turretEnabled);
}

bool Launcher::IsFinishedLaunching()
{

	if (m_cachedLauncherCurrent > m_isLaunchingCurrentThreshold)
	{
		m_launchCurrentTimer.Reset();
		m_launchCurrentTimer.Start();
	}
	else if (m_launchCurrentTimer.Get() > m_isLaunchingTimeThreshold)
	{
		return true;
	}

	return false;
}

void Launcher::UpdateCachedLoggingValues()
{
	units::angle::degree_t hoodError = units::angle::degree_t(std::abs((m_cachedHoodPosition - m_targetHoodAngle).value()));
	units::angular_velocity::revolutions_per_minute_t launcherSpeedError = units::math::abs((m_cachedLauncherVelocity - m_targetLauncherAngularVelocity));
	bool inLaunchzone = IsInLaunchZone();
	auto chassisSpeeds = m_chassis != nullptr ? m_chassis->GetState().Speeds : frc::ChassisSpeeds();
	auto Speed = units::math::sqrt(units::math::abs(chassisSpeeds.vx * chassisSpeeds.vx) + units::math::abs(chassisSpeeds.vy * chassisSpeeds.vy));

	m_hasValidTurretAngle = m_targetCalculator->IsValidTurretAngle();
	m_cachedHoodError = (hoodError < m_hoodAngleThreshold);
	m_cachedLauncherSpeedError = launcherSpeedError < m_launcherVelocityThreshold;
	m_cachedinLaunchzone = (inLaunchzone);
	m_cachedIsChassisSpeed = !AllianceZoneManager::GetInstance()->IsInAllianceZone() ? true : (Speed < m_chassisSpeedThreshold);
	bool turretAtTarget = IsTurretAtTarget();
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "m_cachedHoodError", m_cachedHoodError);
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "m_cachedLauncherSpeedError", m_cachedLauncherSpeedError);
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "m_cachedinLaunchzone", m_cachedinLaunchzone);
	Logger::GetLogger()->LogData(LOGGER_LEVEL::PRINT, m_ntName, "m_targetTurretAngle", turretAtTarget);
}

void Launcher::AgitateSpindexer()
{

	auto currentSpindexerPosition = m_spindexerMotor->GetPosition().GetValue();

	UpdateTargetSpindexerPositionTurnSpindexer(m_minReached ? m_maxSpindexerTarget : m_minSpindexerTarget);

	if (currentSpindexerPosition <= m_minSpindexerTarget)
	{
		m_minReached = true;
	}
	else if (currentSpindexerPosition >= m_maxSpindexerTarget)
	{
		m_minReached = false;
	}
}

void Launcher::InitializeSpindexerTargets()
{
	m_maxSpindexerTarget = m_spindexerMotor->GetPosition().GetValue();
	m_minSpindexerTarget = m_maxSpindexerTarget - m_spindexerTargetAng;
	m_minReached = false;
}